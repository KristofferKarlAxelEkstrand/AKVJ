import fs from 'node:fs';
import path from 'node:path';
import { REPO_ROOT, DEFAULT_WORKFLOW } from './root.js';
import { splitFrontmatter } from './lib/frontmatter.js';
import { parseMessage, listMessageFiles } from './lib/message.js';
import { readAlerts, readTeamHealth } from './lib/health.js';

const workflow = process.argv[2] || DEFAULT_WORKFLOW;
const teamDir = path.join(REPO_ROOT, '.agents/workflows', workflow);
const tasksDir = path.join(teamDir, 'tasks');
const todoDir = path.join(tasksDir, 'todo');
const workingDir = path.join(tasksDir, 'working-on');
const doneDir = path.join(tasksDir, 'done');
const slackDir = path.join(teamDir, 'slack');
const dashboardPath = path.join(slackDir, 'general', 'team-dashboard.md');

const DONE_TASKS_SHOWN = 15;

/**
 * List task files newest-first, reading the contents of at most `limit` of them.
 * `tasks/done/` grows without bound, and the board only ever shows the most
 * recent handful — statting is cheap, reading every file is not.
 */
function getTasks(dir, limit = Infinity) {
  if (!fs.existsSync(dir)) {
    return [];
  }

  let entries = fs.readdirSync(dir)
    .filter(f => f.endsWith('.md') && f !== 'README.md')
    .map(file => ({ file, mtime: fs.statSync(path.join(dir, file)).mtime.getTime() }));

  // Only the capped lists get reordered; uncapped ones keep task-id order,
  // which is what makes the backlog readable.
  if (Number.isFinite(limit)) {
    entries = entries.sort((a, b) => b.mtime - a.mtime).slice(0, limit);
  }

  return entries.map(({ file, mtime }) => {
    const content = fs.readFileSync(path.join(dir, file), 'utf8');
    const meta = splitFrontmatter(content).data;
    // Try to get a title from the first # Heading
    const titleMatch = content.match(/^#\s+(.*)/m);
    const title = titleMatch ? titleMatch[1].trim() : file;
    return { file, title, meta, mtime };
  });
}

const todoTasks = getTasks(todoDir);
const workingTasks = getTasks(workingDir);
const doneTasks = getTasks(doneDir, DONE_TASKS_SHOWN);

// Roles whose in-flight work belongs on the board, discovered from the configs
// so a new agent shows up without editing this script.
const coWorkersDir = path.join(teamDir, 'co-workers');

function getAgentNames() {
  if (!fs.existsSync(coWorkersDir)) {
    return [];
  }
  return fs.readdirSync(coWorkersDir)
    .filter(f => f.endsWith('.prompt.json'))
    .map(f => f.replace(/\.prompt\.json$/, ''))
    .sort();
}

/**
 * Implementers get their own board column. Declared per agent via
 * `"implementer": true`, so adding a developer does not mean remembering to
 * edit this script — the previous hardcoded pair silently left a third
 * developer's work off the board.
 *
 * @param {string} agent
 * @returns {boolean}
 */
function isImplementer(agent) {
  try {
    return JSON.parse(fs.readFileSync(path.join(coWorkersDir, `${agent}.prompt.json`), 'utf8')).implementer === true;
  } catch {
    return false;
  }
}

const agentNames = getAgentNames();
const IMPLEMENTER_ROLES = agentNames.filter(isImplementer);

/**
 * Each agent's pending work, read from the message envelopes rather than
 * inferred from filenames — a message says what it is and who it is for.
 */
function getSlackTasks() {
  const assigned = {};
  for (const agent of agentNames) {
    assigned[agent] = listMessageFiles(path.join(slackDir, agent))
      .map(filePath => parseMessage(filePath))
      .filter(message => message !== null && message.type === 'task')
      .map(message => path.basename(message.filePath));
  }
  return assigned;
}

const assigned = getSlackTasks();

// Generate Markdown
let md = `# Team Dashboard\n\n*Auto-generated by \`generate-dashboard.js\`.*\n\n`;

/**
 * Team health, first thing on the board.
 *
 * This file is what a human opens to see how the team is doing, and it used to
 * say nothing at all about whether the team was even running — liveness lived
 * only in the monitor's stdout, in a tmux window nobody watches. A down agent
 * should be visible in the place people already look.
 */
function healthSection() {
  const team = readTeamHealth(workflow).filter(agent => agent.enabled);
  if (team.length === 0) {
    return '';
  }

  const down = team.filter(agent => agent.state === 'down');
  const alerts = readAlerts(workflow);

  if (!team[0].sessionRunning) {
    return `## 🛑 Team Health\n\nTeam is not running — no tmux session \`${workflow}-agents\`. All ${team.length} agents are down.\n\n`;
  }

  if (down.length === 0 && alerts.length === 0) {
    return `## 💚 Team Health\n\nAll ${team.length} agents up.\n\n`;
  }

  let section = `## 🚨 Team Health\n\n`;
  for (const agent of down) {
    const age = agent.heartbeatAge === null ? 'no heartbeat' : `${agent.heartbeatAge}s since heartbeat`;
    section += `- **${agent.agent} is DOWN** — ${age}, poller pid ${agent.pid ?? 'unknown'} is gone\n`;
  }
  for (const alert of alerts) {
    if (down.some(entry => entry.agent === alert.agent)) {
      continue;
    }
    section += `- **${alert.agent}** has an open alert: ${alert.reason} (\`health/alerts/${alert.agent}.json\`)\n`;
  }
  return `${section}\nRun \`npm run agents:status\` for detail.\n\n`;
}

md += healthSection();

md += `## 📋 Backlog (${todoTasks.length})\n`;
todoTasks.forEach(t => {
  md += `- **${t.file}**: ${t.title} (Priority: ${t.meta.priority || 'none'})\n`;
});

md += `\n## 🚀 In Progress\n`;
IMPLEMENTER_ROLES.forEach(dev => {
  md += `### ${dev}\n`;
  const devTasks = workingTasks.filter(t => t.meta.assignee === dev);
  if (devTasks.length > 0) {
    devTasks.forEach(t => md += `- **${t.file}**: ${t.title}\n`);
  } else {
    md += `- *No tasks assigned in frontmatter*\n`;
  }
  if ((assigned[dev] || []).length > 0) {
    md += `\n**Slack / Active Files:**\n`;
    assigned[dev].forEach(f => md += `- ${f}\n`);
  }
  md += `\n`;
});

md += `## 🔍 Pending QA Audit\n`;
if ((assigned['qa-reviewer'] || []).length > 0) {
  assigned['qa-reviewer'].forEach(f => md += `- ${f}\n`);
} else {
  md += `- *No tasks pending review*\n`;
}

// Anything queued for a role that isn't a developer or QA — previously invisible,
// so a task sitting in a specialist's mailbox never showed up anywhere.
const otherQueues = agentNames
  .filter(agent => !IMPLEMENTER_ROLES.includes(agent) && agent !== 'qa-reviewer')
  .filter(agent => (assigned[agent] || []).length > 0);

if (otherQueues.length > 0) {
  md += `\n## 📥 Other Queues\n`;
  otherQueues.forEach(agent => {
    md += `### ${agent}\n`;
    assigned[agent].forEach(f => md += `- ${f}\n`);
  });
}

md += `\n## ✅ Done (Recent ${DONE_TASKS_SHOWN})\n`;
const recentDone = doneTasks;
if (recentDone.length > 0) {
  recentDone.forEach(t => {
    md += `- **${t.file}**: ${t.title}\n`;
  });
} else {
  md += `- *No completed tasks yet*\n`;
}

fs.writeFileSync(dashboardPath, md);
console.log(`Dashboard successfully generated at ${dashboardPath}`);
